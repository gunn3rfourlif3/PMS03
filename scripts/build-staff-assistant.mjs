#!/usr/bin/env node
/**
 * Carries the Staff manual into the back-office help assistant.
 *
 *   node scripts/build-staff-assistant.mjs
 *
 * `docs/manuals/Staff-Web-Manual.md` is the source of truth. Every section
 * whose heading is followed by `<!-- assistant: <key> -->` becomes one help
 * entry; its first plain paragraph is the purpose line, and every paragraph of
 * the form `**Question?** Answer` becomes a question the assistant can answer,
 * WORD FOR WORD. The key is the back-office route the entry belongs to (`/`,
 * `/leases`), or `#name` for an entry that is searchable but tied to no screen
 * (signing in, the installation, language).
 *
 * Writes two files, both GENERATED — edit the manual, not them:
 *   shared/i18n/assistant-staff.en.ts                    the English strings
 *   web-admin/components/assistant/content-agency.generated.ts  the entry map
 *
 * `web-admin/components/assistant/staff-manual.spec.ts` fails if the manual
 * and the generated files disagree, so a manual edit without a rebuild cannot
 * ship. No dependencies: plain Node, so it runs anywhere the repo does.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const MANUAL = join(ROOT, 'docs', 'manuals', 'Staff-Web-Manual.md');
const OUT_STRINGS = join(ROOT, 'shared', 'i18n', 'assistant-staff.en.ts');
const OUT_CONTENT = join(ROOT, 'web-admin', 'components', 'assistant', 'content-agency.generated.ts');

/** The panel renders plain text: drop markdown emphasis, fold line breaks. */
export const plain = (s) => s.replace(/\*\*/g, '').replace(/\s*\n\s*/g, ' ').trim();

const QA = /^\*\*([^*][^\n]*?\?)\*\* ([\s\S]+)$/;

/** Parse the manual into entries. Exported shape is mirrored by the spec. */
export function parseManual(md) {
  const entries = [];
  for (const chunk of md.split(/^## /m).slice(1)) {
    const [heading, ...rest] = chunk.split('\n');
    const marker = rest.join('\n').match(/^<!-- assistant: (\S+) -->$/m);
    if (!marker) continue;
    const paragraphs = rest.join('\n').split(/\n\s*\n/).map((p) => p.trim()).filter(Boolean);
    let purpose = null;
    const questions = [];
    for (const p of paragraphs) {
      if (p.startsWith('<') || p.startsWith('>') || p === '---' || p.startsWith('*Runs on')) continue;
      const m = p.match(QA);
      if (m) { questions.push({ q: plain(m[1]), a: plain(m[2]) }); continue; }
      if (purpose === null && !p.startsWith('**')) purpose = plain(p);
    }
    if (!purpose) throw new Error(`Section "${heading}" has no purpose paragraph`);
    if (questions.length === 0) throw new Error(`Section "${heading}" has no questions`);
    entries.push({ key: marker[1], section: heading.trim(), purpose, questions });
  }
  return entries;
}

const slugFor = (key) => (key === '/' ? 'dashboard' : key.replace(/^[#/]/, '').replace(/[^a-z0-9]+/gi, '-'));

function build() {
  const entries = parseManual(readFileSync(MANUAL, 'utf8'));
  const keys = new Set();
  for (const e of entries) {
    if (keys.has(e.key)) throw new Error(`Two sections claim ${e.key}`);
    keys.add(e.key);
  }

  const head = `// GENERATED by scripts/build-staff-assistant.mjs from docs/manuals/Staff-Web-Manual.md.
// Do not edit by hand: change the manual and run \`node scripts/build-staff-assistant.mjs\`.
`;
  const strings = [];
  const content = [];
  for (const e of entries) {
    const base = `assistant.staff.${slugFor(e.key)}`;
    strings.push(`  // ${e.section}`);
    strings.push(`  ${JSON.stringify(`${base}.title`)}: ${JSON.stringify(e.section)},`);
    strings.push(`  ${JSON.stringify(`${base}.purpose`)}: ${JSON.stringify(e.purpose)},`);
    const qs = e.questions.map((qa, i) => {
      strings.push(`  ${JSON.stringify(`${base}.q${i + 1}`)}: ${JSON.stringify(qa.q)},`);
      strings.push(`  ${JSON.stringify(`${base}.a${i + 1}`)}: ${JSON.stringify(qa.a)},`);
      return `      { qKey: '${base}.q${i + 1}', aKey: '${base}.a${i + 1}' },`;
    });
    content.push(`  ${JSON.stringify(e.key)}: {
    titleKey: '${base}.title',
    purposeKey: '${base}.purpose',
    questions: [
${qs.join('\n')}
    ],
    manualSection: ${JSON.stringify(e.section)},
  },`);
  }

  writeFileSync(OUT_STRINGS, `${head}
/**
 * The back-office help assistant's English strings, one block per section of
 * the Staff manual. Spread into \`en\` in ./en.ts. Other locales fall back to
 * these until translated.
 */
export const assistantStaffEn = {
${strings.join('\n')}
} as const;
`);

  writeFileSync(OUT_CONTENT, `${head}
import type { AgencyEntryKeys } from './content-agency';

/**
 * One entry per Staff manual section. A key starting with \`/\` is the route the
 * panel shows it on; a key starting with \`#\` is never a route, so that entry is
 * reachable only through the assistant's search.
 */
export const AGENCY_CONTENT: Record<string, AgencyEntryKeys> = {
${content.join('\n')}
};
`);

  const n = entries.reduce((s, e) => s + e.questions.length, 0);
  console.log(`staff assistant: ${entries.length} sections, ${n} questions`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) build();
